const serviceIndex = new Map(services.map((service) => [service.slug, service]))

export function getService(slug: string | undefined) {
  return slug ? serviceIndex.get(slug as ServiceSlug) : undefined
}

export function isServiceSlug(value: string | null | undefined): value is ServiceSlug {
  return value ? serviceIndex.has(value as ServiceSlug) : false
}
